// A band note moved by dragging must survive the next style change, exactly as a note changed
// with the buttons does. Reported by a peer session on 2026-11-02 (theory-level repro: drag path lost
// the edit, event_tune path kept it).
import test from 'node:test';
import assert from 'node:assert/strict';
import {PlayFlow} from '../../../static/ui/stages/play_flow.js';
import {startJam,setJamDirection} from '../../../static/js/theory/jam_session.js';
import {editLeadEvent} from '../../../static/js/theory/event_tune.js';

const base=()=>({id:'t',notes:[],song_cards:[{beat:true,tune:true,under:true,fx:null,big:false,tune_variant:null}],global_context:{root_pc:0,scale_type:'major',bpm:100,meter:'4/4'},lead_patch_id:'warm_keys'});

test('a dragged band note retires generated_by and is not regenerated by the next style change',()=>{
  const doc=startJam(base(),{kind:'pitched',patchId:'warm_keys'});
  const gen=doc.notes.find(n=>n.role==='bass'&&n.generated_by);
  assert.ok(gen,'the jam starts with a generated bass note');
  const flow=Object.assign(Object.create(PlayFlow.prototype),{doc,noteDrag:{},root:{querySelector:()=>null},phraseRange:null,_compile(){this.compiled=(this.compiled||0)+1;},_hearNote(){},_placeNoteButton(){},app:{scheduler:{}}});
  flow._applyNoteDrag(gen,{pitch:70});
  assert.equal(gen.concrete.midi_pitch,70);
  assert.equal(gen.generated_by,undefined);
  assert.equal(gen.edited_from_generator,'musiclab_jam');
  assert.equal(flow.compiled,1);
  const after=setJamDirection(doc,{density:4});
  const kept=after.notes.find(n=>n.id===gen.id);
  assert.ok(kept,'the edited note is still there after a style change');
  assert.equal(kept.concrete.midi_pitch,70);
});

test('the drag path leaves a band note in the ownership state the button path uses',()=>{
  // The button path (event_tune.js) moves generated_by to edited_from_generator; the drag path must match it.
  const doc=startJam(base(),{kind:'pitched',patchId:'warm_keys'});
  const gen=doc.notes.find(n=>n.generated_by);
  const flow=Object.assign(Object.create(PlayFlow.prototype),{doc,noteDrag:{},root:{querySelector:()=>null},phraseRange:null,_compile(){},_hearNote(){},_placeNoteButton(){},app:{scheduler:{}}});
  flow._applyNoteDrag(gen,{step:gen.step});
  assert.equal(gen.generated_by,undefined);
  assert.equal(gen.edited_from_generator,'musiclab_jam');
  assert.equal(gen.provenance,'jam_generated','the origin label stays, as event_tune keeps it');
  assert.equal(typeof editLeadEvent,'function');
});
